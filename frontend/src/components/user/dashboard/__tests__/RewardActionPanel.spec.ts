import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount, flushPromises, mount } from '@vue/test-utils'
import { createI18n } from 'vue-i18n'
import zh from '@/i18n/locales/zh'
import en from '@/i18n/locales/en'
import Panel from '../RewardActionPanel.vue'
const mocks = vi.hoisted(() => ({ status: vi.fn(), wallet: vi.fn(), lottery: vi.fn(), checkin: vi.fn(), withdraw: vi.fn(), consumption: vi.fn(), claim: vi.fn(), sharing: vi.fn(), setSharing: vi.fn(), feed: vi.fn(), refreshUser: vi.fn() }))
vi.mock('@/api/activity', () => ({ getActivityStatus: mocks.status, getActivityWallet: mocks.wallet, getLotteryStatus: mocks.lottery, checkin: mocks.checkin, withdrawActivityWallet: mocks.withdraw, rewardMomentsAPI: { sharing: mocks.sharing, setSharing: mocks.setSharing, feed: mocks.feed } }))
vi.mock('@/api/consumption', () => ({ consumptionAPI: { status: mocks.consumption, claim: mocks.claim } }))
vi.mock('@/stores/auth', () => ({ useAuthStore: () => ({ user: { id: 2 }, refreshUser: mocks.refreshUser }) }))
enableAutoUnmount(afterEach)
function wallet(cents = 350) { return { visible: true, available_cents: cents, available: cents / 100, withdraw_blocked: false } }
function consumption(cents = 200) { return { claimable_cents: cents, awards_enabled: true, blocked: false, wallet: wallet(), campaign: { id: 7, name: '本期活动', claim_until: '2099-01-01T00:00:00Z' } } }
function status() { return { checkin_visible: true, checkin_enabled: true, checkin_eligible: true, checked_today: false, next_reward_cents: 35, checkin_min_spend: 20 } }
const options = (locale = 'zh') => ({ global: { plugins: [createI18n({ legacy: false, locale, messages: { zh, en } })] } })
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>(done => { resolve = done }); return { promise, resolve } }
beforeEach(() => {
  vi.resetAllMocks()
  mocks.status.mockResolvedValue(status()); mocks.wallet.mockResolvedValue(wallet())
  mocks.lottery.mockResolvedValue({ visible: true, enabled: true, awards_enabled: true, remaining_draws: 3 })
  mocks.consumption.mockResolvedValue(consumption())
  mocks.sharing.mockResolvedValue({ allowed: false, display_enabled: false })
  mocks.feed.mockResolvedValue({ enabled: true, items: [] })
  HTMLElement.prototype.scrollIntoView = vi.fn()
})
describe('reward action panel', () => {
  it('interpolates reward amounts and remaining draws in English', async () => {
    const wrapper = mount(Panel, options('en')); await flushPromises()
    expect(wrapper.get('[data-testid=reward-primary]').text()).toBe('Claim $2.00')
    expect(wrapper.get('[data-testid=reward-checkin]').text()).toBe('Check in for $0.35')
    expect(wrapper.get('[data-task=lottery]').text()).toContain('3 draws left')
    expect(wrapper.get('[data-testid=reward-sharing]').element).toHaveProperty('checked', false)
  })
  it('keeps current claim, actual check-in amount, draws and earned wallet separate', async () => {
    const wrapper = mount(Panel, options()); await flushPromises()
    expect(wrapper.get('[data-testid=reward-primary]').text()).toBe('领取 $2.00')
    expect(wrapper.get('[data-testid=reward-checkin]').text()).toContain('$0.35')
    expect(wrapper.get('[data-task=lottery]').text()).toContain('剩余 3 次')
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$3.50')
    expect(mocks.feed).not.toHaveBeenCalled()
    expect(wrapper.get('[data-testid=reward-sharing]').element).toHaveProperty('checked', false)
  })
  it('claims only the displayed campaign and prevents double submission', async () => {
    const pending = deferred<ReturnType<typeof consumption>>()
    mocks.claim.mockReturnValueOnce(pending.promise)
    const wrapper = mount(Panel, options()); await flushPromises()
    await wrapper.get('[data-testid=reward-primary]').trigger('click')
    await wrapper.get('[data-testid=reward-claim]').trigger('click')
    expect(mocks.claim).toHaveBeenCalledTimes(1); expect(mocks.claim).toHaveBeenCalledWith(7)
    mocks.wallet.mockResolvedValue(wallet(550)); mocks.consumption.mockResolvedValue({ ...consumption(0), wallet: wallet(550) })
    pending.resolve({ ...consumption(0), wallet: wallet(550) }); await flushPromises()
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$5.50')
    expect(wrapper.get('[role=status]').text()).toContain('转入余额')
    expect(mocks.refreshUser).not.toHaveBeenCalled()
  })
  it('opens the existing draw and progress flows without drawing or charging', async () => {
    const draw = vi.fn(), progress = vi.fn()
    window.addEventListener('activity-lottery-requested', draw)
    window.addEventListener('activity-claim-requested', progress)
    mocks.consumption.mockResolvedValue(consumption(0))
    const wrapper = mount(Panel, options()); await flushPromises()
    await wrapper.get('[data-testid=reward-lottery]').trigger('click')
    expect(draw).toHaveBeenCalledTimes(1)
    await wrapper.get('[data-testid=reward-claim]').trigger('click')
    expect((progress.mock.calls[0]![0] as CustomEvent).detail.campaignId).toBe(7)
    expect(mocks.withdraw).not.toHaveBeenCalled(); expect(mocks.claim).not.toHaveBeenCalled()
    window.removeEventListener('activity-lottery-requested', draw); window.removeEventListener('activity-claim-requested', progress)
  })
  it('uses the server check-in reward and refreshes the wallet after checking in', async () => {
    mocks.consumption.mockResolvedValue(consumption(0))
    mocks.checkin.mockResolvedValue({ ...status(), checked_today: true, today_reward_cents: 35 })
    const wrapper = mount(Panel, options()); await flushPromises()
    mocks.status.mockResolvedValue({ ...status(), checked_today: true })
    mocks.wallet.mockResolvedValue(wallet(385))
    await wrapper.get('[data-testid=reward-checkin]').trigger('click'); await flushPromises()
    expect(mocks.checkin).toHaveBeenCalledTimes(1)
    expect(wrapper.get('[role=status]').text()).toContain('$0.35')
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$3.85')
  })
  it('keeps successful transfers successful when profile refresh fails', async () => {
    const wrapper = mount(Panel, options()); await flushPromises()
    mocks.withdraw.mockResolvedValue({ ...wallet(0), withdrawn: 3.5 })
    mocks.wallet.mockResolvedValue(wallet(0)); mocks.refreshUser.mockRejectedValue(new Error('profile offline'))
    await wrapper.get('[data-testid=reward-transfer]').trigger('click'); await flushPromises()
    expect(wrapper.get('[role=status]').text()).toContain('3.50')
    expect(wrapper.find('[role=alert]').exists()).toBe(false)
    expect(wrapper.get('[data-testid=reward-transfer]').attributes('disabled')).toBeDefined()
  })
  it('reconciles a timed-out claim with server state before allowing another action', async () => {
    const wrapper = mount(Panel, options()); await flushPromises()
    mocks.claim.mockRejectedValueOnce(new Error('request timed out'))
    mocks.wallet.mockResolvedValue(wallet(550)); mocks.consumption.mockResolvedValue(consumption(0))
    await wrapper.get('[data-testid=reward-primary]').trigger('click'); await flushPromises()
    expect(mocks.claim).toHaveBeenCalledTimes(1)
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$5.50')
    expect(wrapper.get('[data-testid=reward-claim]').text()).toBe('查看进度')
    expect(wrapper.get('[role=alert]').text()).toContain('request timed out')
  })
  it('blocks resubmission when a failed transfer cannot yet be reconciled', async () => {
    const wrapper = mount(Panel, options()); await flushPromises()
    mocks.withdraw.mockRejectedValueOnce(new Error('request timed out'))
    mocks.wallet.mockRejectedValueOnce(new Error('wallet offline'))
    await wrapper.get('[data-testid=reward-transfer]').trigger('click'); await flushPromises()
    expect(wrapper.get('[data-testid=reward-transfer]').attributes('disabled')).toBeDefined()
    await wrapper.get('[data-testid=reward-transfer]').trigger('click')
    expect(mocks.withdraw).toHaveBeenCalledTimes(1)
    mocks.wallet.mockResolvedValue(wallet(0))
    await wrapper.get('.outside-note button').trigger('click'); await flushPromises()
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$0.00')
    expect(wrapper.find('.outside-note').exists()).toBe(false)
    expect(mocks.withdraw).toHaveBeenCalledTimes(1)
  })
  it('preserves reserved claims after activity closure but honors issuance and review blocks', async () => {
    mocks.consumption.mockResolvedValue({ ...consumption(), enabled: false })
    const wrapper = mount(Panel, options()); await flushPromises()
    expect(wrapper.get('[data-testid=reward-primary]').text()).toContain('领取')
    mocks.consumption.mockResolvedValue({ ...consumption(), enabled: false, awards_enabled: false })
    window.dispatchEvent(new Event('focus')); await flushPromises()
    expect(wrapper.get('[data-testid=reward-claim]').text()).toBe('查看进度')
    mocks.wallet.mockResolvedValue({ ...wallet(), withdraw_blocked: true, withdraw_block_reason: 'refund_review' })
    window.dispatchEvent(new Event('focus')); await flushPromises()
    expect(wrapper.get('[data-testid=reward-primary]').text()).toBe('查看奖励钱包')
    expect(wrapper.get('[data-testid=reward-transfer]').attributes('disabled')).toBeDefined()
  })
  it('drops stale personal reads that started before a completed claim', async () => {
    const wrapper = mount(Panel, options()); await flushPromises()
    const old = deferred<ReturnType<typeof wallet>>()
    mocks.wallet.mockReturnValueOnce(old.promise)
    window.dispatchEvent(new Event('focus'))
    mocks.claim.mockResolvedValue({ ...consumption(0), wallet: wallet(550) })
    mocks.wallet.mockResolvedValue(wallet(550)); mocks.consumption.mockResolvedValue(consumption(0))
    await wrapper.get('[data-testid=reward-primary]').trigger('click'); await flushPromises()
    old.resolve(wallet(350)); await flushPromises()
    expect(wrapper.get('[data-task=wallet]').text()).toContain('$5.50')
  })
  it('does not let stale feed responses restore records after consent withdrawal or shutdown', async () => {
    mocks.sharing.mockResolvedValue({ allowed: true, display_enabled: true })
    const old = deferred<{ enabled: boolean; items: unknown[] }>()
    mocks.feed.mockReturnValueOnce(old.promise)
    const wrapper = mount(Panel, options()); await flushPromises()
    mocks.setSharing.mockResolvedValue({ allowed: false, display_enabled: true })
    await wrapper.get('[data-testid=reward-sharing]').setValue(false); await flushPromises()
    old.resolve({ enabled: true, items: [{ id: 'old', alias: 'old', kind: 'checkin', amount_cents: 10, created_at: '2026-11-26T10:00:00Z' }] }); await flushPromises()
    expect(wrapper.find('.community').exists()).toBe(false)
    expect(mocks.setSharing).toHaveBeenCalledWith(false)
    mocks.sharing.mockResolvedValue({ allowed: false, display_enabled: false })
    window.dispatchEvent(new Event('focus')); await flushPromises()
    const calls = mocks.feed.mock.calls.length
    window.dispatchEvent(new Event('focus')); await flushPromises()
    expect(mocks.feed).toHaveBeenCalledTimes(calls)
  })
  it('keeps public updates silent and makes a feed activity focus its personal entry', async () => {
    mocks.sharing.mockResolvedValue({ allowed: false, display_enabled: true })
    mocks.feed.mockResolvedValue({ enabled: true, items: [{ id: 'event', alias: '9a7c', kind: 'lottery', amount_cents: 100, created_at: '2026-11-26T10:00:00Z' }] })
    const wrapper = mount(Panel, { ...options(), attachTo: document.body }); await flushPromises()
    expect(wrapper.find('.community [aria-live], .community [role=status]').exists()).toBe(false)
    await wrapper.get('.feed-kind').trigger('click')
    expect(document.activeElement).toBe(wrapper.get('[data-task=lottery]').element)
    expect(mocks.claim).not.toHaveBeenCalled(); expect(mocks.withdraw).not.toHaveBeenCalled()
    mocks.feed.mockRejectedValue(new Error('offline')); window.dispatchEvent(new Event('focus')); await flushPromises()
    expect(wrapper.find('.community').exists()).toBe(false)
    expect(wrapper.get('[data-testid=reward-claim]').text()).toContain('$2.00')
  })
  it('opens the matching campaign progress when a feed event belongs to another campaign', async () => {
    mocks.sharing.mockResolvedValue({ allowed: false, display_enabled: true })
    mocks.feed.mockResolvedValue({ enabled: true, items: [{ id: 'event', alias: '9a7c', kind: 'consumption', campaign_id: 9, campaign_name: '另一期活动', amount_cents: 100, created_at: '2026-11-26T10:00:00Z' }] })
    const progress = vi.fn()
    window.addEventListener('activity-claim-requested', progress)
    try {
      const wrapper = mount(Panel, options()); await flushPromises()
      await wrapper.get('.feed-kind').trigger('click')
      expect((progress.mock.calls[0]![0] as CustomEvent).detail.campaignId).toBe(9)
      expect(wrapper.get('[data-task=consumption]').text()).toContain('本期活动')
      expect(mocks.claim).not.toHaveBeenCalled(); expect(mocks.withdraw).not.toHaveBeenCalled()
    } finally { window.removeEventListener('activity-claim-requested', progress) }
  })
})
