import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import OperationsWallView from '../OperationsWallView.vue'

const { results, groups, cleanGroup, tasks, showError, showSuccess } = vi.hoisted(() => ({ results: vi.fn(), groups: vi.fn(), cleanGroup: vi.fn(), tasks: vi.fn(), showError: vi.fn(), showSuccess: vi.fn() }))
vi.mock('@/api/admin/operationsConsole', () => ({ operationsApi: { results, groups, cleanGroup, tasks } }))
vi.mock('@/stores/app', () => ({ useAppStore: () => ({ showError, showSuccess }) }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
const select = { props: ['modelValue', 'options'], emits: ['update:modelValue'], template: '<select :value="modelValue" @change="$emit(\'update:modelValue\', Number($event.target.value))"><option v-for="o in options" :key="o.value" :value="o.value">{{ o.label }}</option></select>' }
function render() { return mount(OperationsWallView, { global: { stubs: { Select: select, ConfirmDialog: { props: ['show', 'message'], emits: ['confirm', 'cancel'], template: '<div v-if="show" data-confirm><p>{{ message }}</p><button @click="$emit(\'confirm\')">confirm</button><button @click="$emit(\'cancel\')">cancel</button></div>' }, OperationsResultCard: { props: ['result'], template: '<article :data-id="result.id">{{ result.status }}</article>' } } } }) }
beforeEach(() => {
  vi.resetAllMocks()
  results.mockResolvedValue({ items: [{ id: 1, account_id: 1, account_name: 'A', status: 'failed' }], has_more: false, next_id: 1, next_account_id: 1 })
  groups.mockResolvedValue({ current: [{ id: 10, name: 'Group A', accounts: [{ id: 1, name: 'A', groups: [] }] }, { id: 20, name: 'Group B', accounts: [{ id: 2, name: 'B', groups: [] }] }], past: [{ id: 30, name: 'Old group', accounts: [{ id: 3, name: 'Old account', groups: [] }] }] })
  tasks.mockResolvedValue([])
})
describe('Operations wall', () => {
  it('loads consecutive tests from history immediately without mode buttons', async () => {
    const wrapper = render(); await flushPromises()
    expect(wrapper.get('article').text()).toBe('failed')
    expect(results.mock.calls[0]?.[0]).toMatchObject({ view: 'history', scope: 'current', group_by: 'account' })
    expect(wrapper.findAll('button').some(b => ['operationsConsole.history', 'operationsConsole.latest'].includes(b.text()))).toBe(false)
    wrapper.unmount()
  })
  it('groups four initial tests across plans by account ID and keeps same-name accounts separate', async () => {
    results.mockResolvedValue({ items: [3, 6, 4, 5].map(id => ({ id, account_id: 1, account_name: 'Same name', task_id: id % 2, status: 'failed' })).concat([{ id: 7, account_id: 2, account_name: 'Same name', task_id: 1, status: 'succeeded' }]), has_more: false, account_has_more: { 1: true, 2: false } })
    const wrapper = render(); await flushPromises()
    const rows = wrapper.findAll('[data-account-row]')
    expect(rows).toHaveLength(2)
    expect(rows[0]!.findAll('article').map(card => card.attributes('data-id'))).toEqual(['7'])
    expect(rows[1]!.findAll('article').map(card => card.attributes('data-id'))).toEqual(['6', '5', '4', '3'])
    expect(rows[0]!.text()).toContain('operationsConsole.noMoreResults')
    wrapper.unmount()
  })
  it('appends three older tests only to the clicked account and exhausts the row', async () => {
    const initial = [10, 9, 8, 7].map(id => ({ id, account_id: 1, account_name: 'A', status: 'failed' }))
    results.mockResolvedValueOnce({ items: [...initial, { id: 11, account_id: 2, account_name: 'B', status: 'succeeded' }], has_more: false, account_has_more: { 1: true, 2: false } })
    const wrapper = render(); await flushPromises()
    results.mockResolvedValueOnce({ items: [6, 5, 4].map(id => ({ id, account_id: 1, account_name: 'A', status: 'succeeded' })), has_more: true, next_id: 4 })
    const more = () => wrapper.findAll('[data-account-row]')[1]!.find('button')
    await more().trigger('click'); await flushPromises()
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ view: 'history', account_id: 1, before_id: 7, limit: 3 })
    expect(results.mock.calls.at(-1)?.[0]).not.toHaveProperty('group_by')
    expect(wrapper.findAll('[data-account-row]')[1]!.findAll('article').map(c => c.attributes('data-id'))).toEqual(['10', '9', '8', '7', '6', '5', '4'])
    expect(wrapper.findAll('[data-account-row]')[0]!.findAll('article')).toHaveLength(1)
    results.mockResolvedValueOnce({ items: [{ id: 3, account_id: 1, account_name: 'A', status: 'failed' }], has_more: false, next_id: 3 })
    await more().trigger('click'); await flushPromises()
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ before_id: 4, limit: 3 })
    expect(wrapper.findAll('[data-account-row]')[1]!.findAll('article')).toHaveLength(8)
    expect(wrapper.findAll('[data-account-row]')[1]!.find('button').exists()).toBe(false)
    wrapper.unmount()
  })
  it('keeps filters for older results and allows retry after a failed row request', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('10'); await flushPromises()
    results.mockRejectedValueOnce(new Error('network'))
    await wrapper.find('[data-account-row] button').trigger('click'); await flushPromises()
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ view: 'history', group_id: 10, account_id: 1, before_id: 1, limit: 3 })
    expect(showError).toHaveBeenCalled()
    expect(wrapper.find('[data-account-row] button').attributes('disabled')).toBeUndefined()
    expect(wrapper.findAll('article')).toHaveLength(1)
    wrapper.unmount()
  })
  it('ignores in-flight row results after a filter change', async () => {
    const wrapper = render(); await flushPromises()
    let finish!: (value: unknown) => void
    results.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    await wrapper.find('[data-account-row] button').trigger('click')
    const pendingSignal = results.mock.calls.at(-1)?.[1] as AbortSignal
    await wrapper.findAll('select')[0]!.setValue('10'); await flushPromises()
    expect(pendingSignal.aborted).toBe(true)
    finish({ items: [{ id: 999, account_id: 1, account_name: 'A', status: 'failed' }], has_more: false })
    await flushPromises()
    expect(wrapper.find('article[data-id="999"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('loads more whole account rows using the account cursor', async () => {
    results.mockResolvedValueOnce({ items: [{ id: 10, account_id: 5, account_name: 'A', status: 'failed' }], has_more: true, next_id: 10, next_account_id: 5 })
    const wrapper = render(); await flushPromises()
    results.mockResolvedValueOnce({ items: [{ id: 20, account_id: 2, account_name: 'B', status: 'succeeded' }], has_more: false, next_id: 20, next_account_id: 2 })
    await wrapper.findAll('button').find(b => b.text() === 'operationsConsole.loadMore')!.trigger('click'); await flushPromises()
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ group_by: 'account', before_account_id: 5 })
    expect(results.mock.calls.at(-1)?.[0]).not.toHaveProperty('before_id')
    expect(wrapper.findAll('[data-account-row]')).toHaveLength(2)
    wrapper.unmount()
  })
  it('filters account choices by group and clears an invalid account selection', async () => {
    const wrapper = render(); await flushPromises()
    const selects = wrapper.findAll('select')
    await selects[1]!.setValue('2'); await flushPromises()
    await selects[0]!.setValue('10'); await flushPromises()
    expect(selects[1]!.text()).toContain('A')
    expect(selects[1]!.text()).not.toContain('B')
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ group_id: 10, account_id: undefined })
    wrapper.unmount()
  })
  it('scrolls the account row horizontally with the wheel and releases page scroll at the edges', async () => {
    const wrapper = render(); await flushPromises()
    const track = wrapper.get('.operations-result-track').element as HTMLElement
    Object.defineProperties(track, { clientWidth: { value: 900 }, scrollWidth: { value: 2100 } })
    const wheel = (deltaY: number, options: WheelEventInit = {}) => {
      const event = new WheelEvent('wheel', { deltaY, bubbles: true, cancelable: true, ...options })
      track.dispatchEvent(event)
      return event
    }
    expect(wheel(120).defaultPrevented).toBe(true)
    expect(track.scrollLeft).toBe(120)
    wheel(-3, { deltaMode: 1 })
    expect(track.scrollLeft).toBe(72)
    wheel(0, { deltaX: 200 })
    expect(track.scrollLeft).toBe(272)
    expect(wheel(80, { ctrlKey: true }).defaultPrevented).toBe(false)
    expect(track.scrollLeft).toBe(272)
    wheel(2000)
    expect(track.scrollLeft).toBe(1200)
    expect(wheel(100).defaultPrevented).toBe(false)
    wheel(-2000)
    expect(track.scrollLeft).toBe(0)
    expect(wheel(-100).defaultPrevented).toBe(false)
    wrapper.unmount()
  })
  it('switches group/account choices and result scope together and exposes cleanup only in past', async () => {
    const wrapper = render(); await flushPromises()
    expect(wrapper.findAll('select')[0]!.text()).toContain('Group A')
    expect(wrapper.findAll('select')[0]!.text()).not.toContain('Old group')
    expect(wrapper.findAll('button').some(b => b.text() === 'operationsConsole.cleanGroup')).toBe(false)
    await wrapper.findAll('[role="tab"]')[1]!.trigger('click'); await flushPromises()
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ scope: 'past', group_id: undefined, account_id: undefined })
    expect(wrapper.findAll('select')[0]!.text()).toContain('Old group')
    expect(wrapper.findAll('select')[0]!.text()).not.toContain('Group A')
    expect(wrapper.findAll('select')[1]!.text()).toContain('Old account')
    const button = wrapper.findAll('button').find(b => b.text() === 'operationsConsole.cleanGroup')!
    expect(button.attributes('disabled')).toBeDefined()
    await wrapper.findAll('select')[0]!.setValue('30'); await flushPromises()
    expect(button.attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it('confirms group-specific cleanup and reloads both catalog and results', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.findAll('[role="tab"]')[1]!.trigger('click'); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('30'); await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === 'operationsConsole.cleanGroup')!.trigger('click')
    expect(cleanGroup).not.toHaveBeenCalled()
    expect(wrapper.find('[data-confirm]').exists()).toBe(true)
    cleanGroup.mockResolvedValueOnce({ removed: 2, detached: 1, failed: 0 })
    groups.mockResolvedValue({ current: [], past: [] })
    await wrapper.find('[data-confirm] button').trigger('click'); await flushPromises()
    expect(cleanGroup).toHaveBeenCalledWith(30)
    expect(showSuccess).toHaveBeenCalledWith('operationsConsole.cleaned')
    expect(wrapper.find('[data-confirm]').exists()).toBe(false)
    expect(wrapper.findAll('select')[0]!.text()).not.toContain('Old group')
    wrapper.unmount()
  })
  it('keeps different account choices for a group present in both tabs', async () => {
    groups.mockResolvedValue({ current: [{ id: 10, name: 'Mixed group', accounts: [{ id: 1, name: 'Configured account', groups: [] }] }], past: [{ id: 10, name: 'Mixed group', accounts: [{ id: 2, name: 'Removed account', groups: [] }] }] })
    const wrapper = render(); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('10'); await flushPromises()
    expect(wrapper.findAll('select')[1]!.text()).toContain('Configured account')
    expect(wrapper.findAll('select')[1]!.text()).not.toContain('Removed account')
    await wrapper.findAll('[role="tab"]')[1]!.trigger('click'); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('10'); await flushPromises()
    expect(wrapper.findAll('select')[1]!.text()).toContain('Removed account')
    expect(wrapper.findAll('select')[1]!.text()).not.toContain('Configured account')
    expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ scope: 'past', group_id: 10 })
    wrapper.unmount()
  })
  it('reloads an expanded row when its account is removed from detection configuration', async () => {
    vi.useFakeTimers()
    const wrapper = render()
    try {
      await flushPromises()
      results.mockResolvedValueOnce({ items: [{ id: 0, account_id: 1, account_name: 'A', status: 'succeeded' }], has_more: false })
      await wrapper.find('[data-account-row] button').trigger('click'); await flushPromises()
      groups.mockResolvedValue({ current: [], past: [{ id: 10, name: 'Group A', accounts: [{ id: 1, name: 'A', groups: [] }] }] })
      results.mockResolvedValue({ items: [], has_more: false })
      await vi.advanceTimersByTimeAsync(5000); await flushPromises()
      expect(wrapper.findAll('article')).toHaveLength(0)
      expect(results.mock.calls.at(-1)?.[0]).toMatchObject({ scope: 'current', group_by: 'account' })
    } finally { wrapper.unmount(); vi.useRealTimers() }
  })
  it('cancels cleanup without deleting anything and reports failed storage cleanup', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.findAll('[role="tab"]')[1]!.trigger('click'); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('30'); await flushPromises()
    const open = async () => { await wrapper.findAll('button').find(b => b.text() === 'operationsConsole.cleanGroup')!.trigger('click') }
    await open(); await wrapper.findAll('[data-confirm] button')[1]!.trigger('click')
    expect(cleanGroup).not.toHaveBeenCalled()
    expect(wrapper.find('[data-confirm]').exists()).toBe(false)
    await open(); cleanGroup.mockResolvedValueOnce({ removed: 0, detached: 0, failed: 1 })
    await wrapper.find('[data-confirm] button').trigger('click'); await flushPromises()
    expect(showError).toHaveBeenCalledWith('operationsConsole.cleanupPartial')
    expect(showSuccess).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('keeps results and the confirmation when cleanup is rejected', async () => {
    const wrapper = render(); await flushPromises()
    await wrapper.findAll('[role="tab"]')[1]!.trigger('click'); await flushPromises()
    await wrapper.findAll('select')[0]!.setValue('30'); await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === 'operationsConsole.cleanGroup')!.trigger('click')
    cleanGroup.mockRejectedValueOnce({ response: { data: { message: 'Group is currently configured' } } })
    await wrapper.find('[data-confirm] button').trigger('click'); await flushPromises()
    expect(showError).toHaveBeenCalledWith('Group is currently configured')
    expect(wrapper.find('[data-confirm]').exists()).toBe(true)
    expect(wrapper.findAll('article')).toHaveLength(1)
    wrapper.unmount()
  })
})
